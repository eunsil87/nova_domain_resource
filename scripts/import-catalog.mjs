import { readFile, writeFile } from "node:fs/promises";
const source = new URL(
  "../docs/catalog/NOVA_SO_RO_L2_L4_Functional_Catalog_v3.0.md",
  import.meta.url,
);
const text = await readFile(source, "utf8");
const rows = text
  .split("\n")
  .map((line) =>
    line
      .trim()
      .replace(/^\||\|$/g, "")
      .split("|")
      .map((x) => x.trim()),
  )
  .filter((c) => c.length === 15 && ["EPC", "SVC", "RSC"].includes(c[0]));
const levels = ["domains", "l2", "subcomponents", "l3", "l4"],
  maps = Object.fromEntries(levels.map((k) => [k, new Map()]));
for (const row of rows) {
  const [
    domain,
    l2,
    name2,
    ko2,
    sc,
    nameSC,
    koSC,
    l3,
    name3,
    ko3,
    l4,
    name4,
    ko4,
    description,
    required,
  ] = row;
  const nodes = [
    [domain, domain, null],
    [l2, name2, ko2],
    [sc, nameSC, koSC],
    [l3, name3, ko3],
    [l4, name4, ko4],
  ];
  let parentId = null;
  for (let i = 0; i < nodes.length; i++) {
    const [code, name, koreanName] = nodes[i],
      key = levels[i],
      id = `cat-${key}-${code}`;
    const item = {
      id,
      code,
      name,
      koreanName,
      parentId,
      ...(key === "subcomponents" ? { assigneeIds: [] } : {}),
      ...(key === "l4" ? { description, required: required === "필수" } : {}),
    };
    if (
      maps[key].has(code) &&
      JSON.stringify(maps[key].get(code)) !== JSON.stringify(item)
    )
      throw Error(`Inconsistent catalog: ${code}`);
    maps[key].set(code, item);
    parentId = id;
  }
  if (!["필수", "옵션"].includes(required))
    throw Error(`Invalid requirement: ${l4}`);
}
const catalog = {
  version: 1,
  sourceVersion: "3.0",
  ...Object.fromEntries(levels.map((k) => [k, [...maps[k].values()]])),
};
if (
  JSON.stringify(levels.map((k) => catalog[k].length)) !==
    JSON.stringify([3, 5, 12, 20, 106]) ||
  catalog.l4.filter((x) => x.required).length !== 86
)
  throw Error("Catalog counts mismatch.");
await writeFile(
  new URL("../src/catalog-baseline.js", import.meta.url),
  "// Generated by scripts/import-catalog.mjs from the supplied v3.0 catalog.\nexport const CATALOG_BASELINE = " +
    JSON.stringify(catalog, null, 2) +
    ";\n",
);
console.log(
  "Catalog baseline verified: 3 domains / 5 L2 / 12 Sub Components / 20 L3 / 106 L4 (86 required, 20 optional).",
);
